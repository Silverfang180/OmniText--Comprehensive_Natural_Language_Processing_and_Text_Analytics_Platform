"""API Router for managing fine-tuning experiments and model promotion."""

from typing import Any

from fastapi import APIRouter, Depends, HTTPException, Request, status
from sqlalchemy import select, update
from sqlalchemy.ext.asyncio import AsyncSession

from omnitext.api.v1.deps import db_session_dependency, get_current_user
from omnitext.api.v1.schemas.envelope import ResponseEnvelope, ResponseMeta
from omnitext.api.v1.schemas.experiment import (
    ExperimentCreateRequest,
    ExperimentResponse,
)
from omnitext.db.models import Job, User
from omnitext.db.models.benchmark import ModelRegistryEntry
from omnitext.db.models.experiment import Experiment
from omnitext.services.analysis_service import AnalysisService

router = APIRouter(prefix="/experiments", tags=["Experiments"])


@router.get("")
async def list_experiments(
    request: Request,
    db: AsyncSession = Depends(db_session_dependency),
    current_user: User = Depends(get_current_user),
) -> ResponseEnvelope[list[ExperimentResponse]]:
    """List authenticated user's fine-tuning experiments."""
    request_id = getattr(request.state, "request_id", None)

    stmt = (
        select(Experiment)
        .where(Experiment.user_id == current_user.id)
        .order_by(Experiment.created_at.desc())
    )
    res = await db.execute(stmt)
    experiments = res.scalars().all()

    resp_list = [ExperimentResponse.model_validate(e) for e in experiments]

    return ResponseEnvelope[list[ExperimentResponse]](
        data=resp_list,
        meta=ResponseMeta(request_id=request_id),
        error=None,
    )


@router.get("/{experiment_id}")
async def get_experiment(
    experiment_id: int,
    request: Request,
    db: AsyncSession = Depends(db_session_dependency),
    current_user: User = Depends(get_current_user),
) -> ResponseEnvelope[ExperimentResponse]:
    """Retrieve details of a specific fine-tuning experiment."""
    request_id = getattr(request.state, "request_id", None)

    experiment = await db.get(Experiment, experiment_id)
    if not experiment:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Experiment not found.",
        )

    # Ownership enforcement
    if experiment.user_id != current_user.id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access forbidden to requested experiment resource.",
        )

    return ResponseEnvelope[ExperimentResponse](
        data=ExperimentResponse.model_validate(experiment),
        meta=ResponseMeta(request_id=request_id),
        error=None,
    )


@router.post("")
async def create_experiment(
    request_data: ExperimentCreateRequest,
    request: Request,
    db: AsyncSession = Depends(db_session_dependency),
    current_user: User = Depends(get_current_user),
) -> ResponseEnvelope[ExperimentResponse]:
    """Trigger a new NER fine-tuning experiment run."""
    request_id = getattr(request.state, "request_id", None)

    # Create Experiment row
    experiment = Experiment(
        user_id=current_user.id,
        name=request_data.name,
        base_model_id=request_data.base_model_id,
        hyperparameters=request_data.hyperparameters,
        status="pending",
    )
    db.add(experiment)
    await db.commit()
    await db.refresh(experiment)

    # Queue background worker job
    job = Job(
        type="ner_finetune",
        status="pending",
        payload={"experiment_id": experiment.id},
    )
    db.add(job)
    await db.commit()

    return ResponseEnvelope[ExperimentResponse](
        data=ExperimentResponse.model_validate(experiment),
        meta=ResponseMeta(request_id=request_id),
        error=None,
    )


@router.post("/{experiment_id}/promote")
async def promote_fine_tuned_model(
    experiment_id: int,
    request: Request,
    db: AsyncSession = Depends(db_session_dependency),
    current_user: User = Depends(get_current_user),
) -> ResponseEnvelope[dict[str, Any]]:
    """Promote the model generated by a completed experiment to active status for NER task."""
    request_id = getattr(request.state, "request_id", None)

    experiment = await db.get(Experiment, experiment_id)
    if not experiment:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Experiment not found.",
        )

    # Ownership check
    if experiment.user_id != current_user.id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access forbidden to requested experiment resource.",
        )

    # Verify status is completed
    if experiment.status != "completed" or not experiment.fine_tuned_model_id:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Only successfully completed experiments can be promoted.",
        )

    # Deactivate all active models for task "ner"
    deact_stmt = (
        update(ModelRegistryEntry)
        .where(ModelRegistryEntry.task == "ner")
        .values(is_active=False)
    )
    await db.execute(deact_stmt)

    # Check if entry already exists in registry
    reg_stmt = select(ModelRegistryEntry).where(
        ModelRegistryEntry.task == "ner",
        ModelRegistryEntry.model_id == experiment.fine_tuned_model_id,
    )
    reg_res = await db.execute(reg_stmt)
    reg_entry = reg_res.scalar_one_or_none()

    if reg_entry:
        reg_entry.is_active = True
    else:
        new_entry = ModelRegistryEntry(
            task="ner",
            model_id=experiment.fine_tuned_model_id,
            version="main",
            is_active=True,
            is_fine_tuned=True,
        )
        db.add(new_entry)

    # Update experiment status to reflect promotion
    experiment.status = "promoted"
    await db.commit()

    # Clear cached adapter for the task to force reload
    AnalysisService._loaded_adapters.pop("ner", None)

    data = {
        "success": True,
        "message": f"Successfully promoted '{experiment.fine_tuned_model_id}' to active model for NER task.",
    }

    return ResponseEnvelope[dict[str, Any]](
        data=data,
        meta=ResponseMeta(request_id=request_id),
        error=None,
    )


@router.post("/{experiment_id}/reject")
async def reject_fine_tuned_model(
    experiment_id: int,
    request: Request,
    db: AsyncSession = Depends(db_session_dependency),
    current_user: User = Depends(get_current_user),
) -> ResponseEnvelope[dict[str, Any]]:
    """Explicitly reject the fine-tuned model results for an experiment."""
    request_id = getattr(request.state, "request_id", None)

    experiment = await db.get(Experiment, experiment_id)
    if not experiment:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Experiment not found.",
        )

    # Ownership check
    if experiment.user_id != current_user.id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access forbidden to requested experiment resource.",
        )

    # Verify status allows rejection
    if experiment.status not in ["completed", "failed"]:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Only completed or failed experiments can be archived/rejected.",
        )

    # Update status to rejected
    experiment.status = "rejected"
    await db.commit()

    data = {
        "success": True,
        "message": f"Experiment ID {experiment_id} successfully archived as rejected.",
    }

    return ResponseEnvelope[dict[str, Any]](
        data=data,
        meta=ResponseMeta(request_id=request_id),
        error=None,
    )
